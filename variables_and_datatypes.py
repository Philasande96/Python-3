#Revising Python variables and datatypes
#No need to declare the datatype, Python  automatically assigns the datatype based on the value assigned to the variable


#int
age = 90

#Float 
pi = 3.14

#String
Fullname = "Philasande Mathafeni"

#Boolean
is_adult = True

#Printing the variables and their datatypes
print("Age:", age, "Datatype:", type(age))
print("Pi:", pi, "Datatype:", type(pi))
print("Fullname:", Fullname, "Datatype:", type(Fullname))
print("Is Adult:", is_adult, "Datatype:", type(is_adult))   

